# C35 resource ceilings: the deterministic pipeline (no AI features) is bounded
# by an elapsed-time budget so a huge repository ends as an explicit PARTIAL
# analysis instead of an unbounded run.
DEFAULT_TIME_BUDGET_SECONDS = 600
TIME_BUDGET_ENV = "ATTACKMAP_TIME_BUDGET_SECONDS"


def resolve_time_budget_seconds(explicit: int | None = None) -> int:
    """Deterministic elapsed ceiling: explicit value → env override → 600s."""
    raw: object = explicit if explicit is not None else os.environ.get(TIME_BUDGET_ENV)
    if raw is None or str(raw).strip() == "":
        return DEFAULT_TIME_BUDGET_SECONDS
    try:
        value = int(str(raw).strip())
    except ValueError:
        raise AnalysisConfigurationError(
            f"{TIME_BUDGET_ENV} / time budget must be a positive integer, got {raw!r}."
        ) from None
    if value < 1:
        raise AnalysisConfigurationError(
            f"{TIME_BUDGET_ENV} / time budget must be >= 1 second; got {value}."
        )
    return value


@dataclass
class StageTiming:
    name: str
    milliseconds: int


def _engine_utc_now() -> str:
    return datetime.now(UTC).isoformat()


@dataclass
class RunState:
    """Mutable per-run accumulator; the frozen ``spec`` is its configuration."""

    spec: RunSpec
    analyzers: list = field(default_factory=list)
    analyzer_run_plan: AnalyzerRunPlan | None = None
    scan: ScanResult | None = None
    surfaces: list[AttackSurface] = field(default_factory=list)
    findings: list[Finding] = field(default_factory=list)
    paths: list[AttackPath] = field(default_factory=list)
    overlay: SecurityOverlay | None = None
    suppressed: list[SuppressedFinding] = field(default_factory=list)
    timings: list[StageTiming] = field(default_factory=list)
    llm_usage: dict[str, int] = field(default_factory=dict)
    ai_outputs: dict[str, bool] = field(default_factory=dict)
    exit_code: int = 0
    errors: list[dict[str, str]] = field(default_factory=list)
    scan_started_at: str = field(default_factory=lambda: _engine_utc_now())
    scan_finished_at: str | None = None
    scan_outcome: str | None = None
    diagnostic_stages: list[DiagnosticStage] = field(default_factory=list)
    time_budget: TimeBudget | None = None
    attempt_started: float = field(default_factory=time.perf_counter, repr=False)
    events: EventLog | None = field(default=None, repr=False)

    def finish_scan(self, outcome: str) -> None:
        if self.scan_finished_at is None:
            self.scan_finished_at = _engine_utc_now()
            self.scan_outcome = outcome

    def scan_timing(self) -> dict[str, str | None]:
        return {"schema_version": "1.0", "clock": "engine_utc",
                "scope": "analysis_pipeline_before_publication",
                "started_at": self.scan_started_at, "finished_at": self.scan_finished_at,
                "outcome": self.scan_outcome}


@contextmanager
def _diagnostic_phase(state: RunState, name: str):
    started = time.perf_counter()
    outcome = "completed"
    events = state.events
    if events is not None:
        events.stage(name, "start")
    try:
        yield
    except BaseException as exc:
        outcome = "cancelled" if isinstance(exc, KeyboardInterrupt) else "failed"
        if events is not None:
            events.stage(name, "cancelled" if outcome == "cancelled" else "error",
                         ms=int((time.perf_counter() - started) * 1000),
                         detail=type(exc).__name__)
        raise
    finally:
        elapsed_ms = int((time.perf_counter() - started) * 1000)
        state.timings.append(StageTiming(name=name, milliseconds=elapsed_ms))
        state.diagnostic_stages.append(DiagnosticStage(stage_id=name, outcome=outcome,
                                                       duration_milliseconds=elapsed_ms))
        if events is not None and outcome == "completed":
            events.stage(name, "end", ms=elapsed_ms)


def _timed(state: RunState, name: str, fn: Callable[[], None]) -> None:
    with _diagnostic_phase(state, name):
        fn()


def _diagnostic_context(state: RunState, outcome: str) -> DiagnosticContext:
    coverage, resources = scan_diagnostic(state.scan)
    metadata = []
    for analyzer in state.analyzers:
        declared = get_analyzer_metadata(analyzer)
        metadata.append({"name": declared.name, "version": declared.version,
                         "version_status": "declared" if "version" in declared.model_fields_set else "unknown"})
    context = DiagnosticContext(outcome=outcome,
        policy_outcome=("failed" if state.exit_code else "passed") if outcome == "completed" else "not_evaluated",
        stages=[*state.diagnostic_stages, DiagnosticStage(stage_id="analysis_pipeline", outcome=outcome,
            duration_milliseconds=max(0, int((time.perf_counter() - state.attempt_started) * 1000)))],
        analyzers=_analyzers(metadata, status="complete" if state.analyzers else "unknown"),
        coverage=coverage, resource_events=resources)
    return context


def _write_text(path: Path, text: str) -> None:
    path = Path(path)
    try:
        safe_write_text(ensure_output_dir(path.parent), path, text)
    except UnsafePathError as exc:
        emit_text(f"Error: {exc}", err=True)
        raise AnalysisExit(2) from exc


def write_run_manifest(state: RunState, output: Path) -> None:
    """Always written, independent of ``--format``. No source text, no secrets."""
    scan = state.scan
    findings = state.findings
    by_sev = Counter(f.severity for f in findings)
    payload = {
        "engine_version": __version__,
        "diagnostic_context": _diagnostic_context(state, state.scan_outcome or "unknown").model_dump(mode="json"),
        "scan_timing": state.scan_timing(),
        "analyzers": [
            {
                "name": get_analyzer_metadata(a).name,
                "version": get_analyzer_metadata(a).version,
            }
            for a in state.analyzers
        ],
        "stages": [{"name": t.name, "milliseconds": t.milliseconds} for t in state.timings],
        "files_scanned": scan.files_scanned if scan is not None else 0,
        "analyzer_errors": [
            {"analyzer": e.analyzer, "error_type": e.error_type, "message": e.message}
            for e in (scan.analyzer_errors if scan is not None else [])
        ],
        "limitation_count": len(scan.limitations) if scan is not None else 0,
        "findings_by_severity": {
            "high": by_sev.get("high", 0),
            "medium": by_sev.get("medium", 0),
            "low": by_sev.get("low", 0),
        },
        "llm_usage": dict(state.llm_usage),
    }
    analyzer_ledger = scan.analyzer_run_ledger if scan is not None else None
    if analyzer_ledger is None and state.analyzer_run_plan is not None:
        analyzer_ledger = state.analyzer_run_plan.ledger
    payload["analyzer_run_ledger"] = analyzer_ledger.model_dump(mode="json") if analyzer_ledger is not None else None
    ai = state.spec.ai
    if ai.enabled or ai.hunt or ai.remediate or ai.triage:
        ledger = current_budget()
        if ledger is not None:
            payload["ai_allowance"] = ledger.snapshot()
    if ai.desktop_mode is not None:
        from .desktop_ai import manifest_ai_result
        from .llm_review import DEFAULT_EFFORT, OPENAI_EFFORT_MAP
        ledger = current_budget()
        payload["desktop_ai"] = manifest_ai_result(ai.desktop_mode, Path(output),
                                                  ledger.snapshot() if ledger is not None else None, state.ai_outputs)
        effort = ai.effort or DEFAULT_EFFORT
        payload["desktop_ai"]["service_parameters"] = {
            "requested_effort": ai.effort,
            "mapped_effort": None if ai.desktop_mode == "none" else
                OPENAI_EFFORT_MAP.get(effort, "high") if ai.provider == "openai" else effort,
            "provider": ai.provider, "requested_model": ai.model,
            "backend": ai.backend, "speed": ai.speed,
            "jury_votes": ai.verify_votes if ai.desktop_mode == "hunt_verify" else None,
        }
    if state.time_budget is not None:
        payload["time_budget"] = {
            "seconds": state.time_budget.seconds,
            "exceeded": state.time_budget.exceeded,
            **({"exceeded_before": state.time_budget.exceeded_stage}
               if state.time_budget.exceeded_stage is not None else {}),
        }
    _write_text(Path(output) / "run-manifest.json", json.dumps(payload, indent=2) + "\n")


def _warn_if_nothing_scanned(scan: ScanResult, echo: Callable[..., None]) -> None:
    if scan.files_scanned:
        return
    root = Path(scan.root)
    try:
        has_files = any(p.is_file() for p in root.iterdir())
    except OSError:
        has_files = False
    if has_files or any(root.glob("*/*")):
        echo(
            "Warning: no source files were scanned. Check the path, and whether every file "
            "is under a skipped directory (node_modules, dist, build, out, target, …) or in an "
            "unsupported language.",
            err=True,
        )


def _echo_opt_in_hint(names: list[str], echo: Callable[..., None]) -> None:
    if names:
        echo(
            f"Opt-in analyzers match this repo but were not run: {', '.join(names)}. "
            f"Enable with {' '.join(f'-m {n}' for n in names)}.",
            err=True,
        )


def _run_scan(
    spec: RunSpec,
    *,
    repo_path: Path,
    output: Path,
    analyzers: list | None = None,
    echo: Callable[..., None] = emit_text,
    state: RunState | None = None,
) -> RunState:
    """Run one repository through recon, translation, reports, and optional LLM."""
    ai = spec.ai
    state = state if state is not None else RunState(spec=spec)
    output = Path(output)
    # AR003: structured run event log. Additive only — stdout progress is
    # untouched, and the log is persisted into the generation directory by
    # _run_scan_published before the pointer swap.
    if state.events is None:
        state.events = EventLog(run_id=spec.run_id or make_run_id())

    with _diagnostic_phase(state, "request_validation"):
        if spec.fail_on_new_high and spec.baseline is None:
            raise AnalysisConfigurationError("--fail-on-new-high requires --baseline to be set.")
        if spec.fail_on_new_suppression and spec.baseline is None:
            raise AnalysisConfigurationError("--fail-on-new-suppression requires --baseline to be set.")
        if spec.baseline is not None:
            baseline_path = Path(spec.baseline)
            if not baseline_path.exists():
                raise AnalysisConfigurationError(f"Baseline report not found: {baseline_path}")

    llm_display = (
        "OpenAI-compatible provider" if ai.backend == "api" else "Codex"
    ) if ai.provider == "openai" else "Claude"
    if ai.provider == "openai" and ai.speed == "fast" and (ai.enabled or ai.hunt or ai.remediate):
        echo(
            "Note: --llm-speed fast is Claude-only; ignoring it for the OpenAI provider.",
            err=True,
        )

    opt_in_matches: list[str] = []
    captured_index: RepoIndex | None = None
    # AR028 concurrency envelope for TimeBudget (run_budget.py): its only
    # write is the single-reference ``exceeded_stage`` assignment in check()
    # — atomic under the GIL — and this pipeline calls check()/tick() only
    # from this thread (the AR027 scheduler pool touches the budget never;
    # fleet workers each own their budget through a ContextVar). Reads stay
    # lock-free; no lock is added.
    budget = TimeBudget(resolve_time_budget_seconds(spec.budget.time_budget_seconds))
    state.time_budget = budget
    scan_progress = create_progress(spec.progress_format, no_progress=spec.no_progress)

    def _select() -> None:
        nonlocal captured_index
        with time_budget_scope(budget):
            captured_index = RepoIndex.build(repo_path)
            state.analyzer_run_plan = AnalyzerRunPlan(Path(repo_path).resolve(), captured_index, AnalyzerRunLedger(
                selection_mode="automatic" if analyzers is None else "explicit",
                inventory_scope="registered_candidates" if analyzers is None else "supplied_candidates",
                profile_id=spec.analyzer.profile_id))
            state.analyzers = resolve_run_analyzers(
                repo_path, analyzers=analyzers, opt_in_matches=opt_in_matches,
                run_plan=state.analyzer_run_plan,
                progress=scan_progress,
                allow_untrusted=spec.analyzer.allow_untrusted or None,
            )

    try:
        _timed(state, "select_analyzers", _select)
        _echo_opt_in_hint(opt_in_matches, echo)
    except BaseException:
        scan_progress.done()
        raise

    # C35 elapsed-time budget: one cheap perf_counter read per stage boundary.
    # A breach skips later optional stages and still publishes, so the run ends
    # as a COMPLETED analysis whose scan carries explicit partial coverage.

    def _deadline_hit(skipped_stage: str) -> bool:
        if not budget.check(skipped_stage):
            return False
        if state.scan is None:
            state.scan = ScanResult(root=str(repo_path))
        scan_now = state.scan
        if state.events is not None:
            state.events.stage(skipped_stage, "skip",
                               detail=f"time budget of {budget.seconds}s expired")
        if state.analyzer_run_plan is not None and not state.analyzer_run_plan.ledger.execution_complete:
            state.analyzer_run_plan.skip_for_deadline()
            scan_now.analyzer_run_ledger = state.analyzer_run_plan.ledger.model_copy(deep=True)
        note = (
            f"elapsed-time budget of {budget.seconds}s expired before {skipped_stage}; "
            "the remaining optional stages were skipped — ANALYSIS IS PARTIAL, not "
            "complete. Raise the ceiling with --time-budget-seconds or "
            f"{TIME_BUDGET_ENV}."
        )
        if note not in scan_now.limitations:
            scan_now.limitations.append(note)
        record = AnalyzerError(
            analyzer="pipeline",
            error_type="time_budget_exceeded",
            message=(
                f"deterministic run deadline ({budget.seconds}s) reached; "
                f"{skipped_stage} and later optional stages skipped"
            ),
        )
        if record not in scan_now.analyzer_errors:
            scan_now.analyzer_errors.append(record)
        echo(f"Warning: {note}", err=True)
        return True

    if not _deadline_hit("scan_and_merge"):
        def _scan() -> None:
            with time_budget_scope(budget):
                state.scan = analyze_repository(
                    repo_path,
                    run_plan=state.analyzer_run_plan,
                    progress=scan_progress,
                    recall=spec.features.recall,
                    strict=spec.analyzer.strict,
                    isolated_analyzers=spec.analyzer.isolated,
                    incremental=spec.features.incremental,
                    index=captured_index,
                    events=state.events,
                    workers=max(1, int(spec.scheduler.workers)),
                )

        def _recover_partial_scan(exc: BudgetExpired) -> None:
            """Convert an intra-stage budget breach into a publishable partial
            scan (AR007/AC-010): keep whatever the interrupted stage built,
            record the limitation, and let later stages skip via the deadline
            they will now observe on their own."""
            partial = getattr(exc, "partial", None)
            scan_now = partial if isinstance(partial, ScanResult) else ScanResult(root=str(repo_path))
            state.scan = scan_now
            if state.events is not None:
                state.events.stage("scan_and_merge", "skip",
                                   detail=f"time budget of {budget.seconds}s expired inside the stage")
            note = (
                f"elapsed-time budget of {budget.seconds}s expired inside the scan stage; "
                "the scan stopped early - ANALYSIS IS PARTIAL, not complete. "
                f"Raise the ceiling with --time-budget-seconds or {TIME_BUDGET_ENV}."
            )
            if note not in scan_now.limitations:
                scan_now.limitations.append(note)
            record = AnalyzerError(
                analyzer="pipeline",
                error_type="time_budget_exceeded",
                message=(
                    f"deterministic run deadline ({budget.seconds}s) reached inside the "
                    "scan stage; the scan stopped early with partial coverage"
                ),
            )
            if record not in scan_now.analyzer_errors:
                scan_now.analyzer_errors.append(record)
            if state.analyzer_run_plan is not None and not state.analyzer_run_plan.ledger.execution_complete:
                state.analyzer_run_plan.skip_for_deadline()
                scan_now.analyzer_run_ledger = state.analyzer_run_plan.ledger.model_copy(deep=True)
            echo(f"Warning: {note}", err=True)

        try:
            _timed(state, "scan_and_merge", _scan)
        except BudgetExpired as exc:
            scan_progress.done()
            _recover_partial_scan(exc)
        except BaseException:
            scan_progress.done()
            raise
    else:
        scan_progress.done()
    scan = state.scan
    assert scan is not None

    # The index this run's _select stage captured (C33/AM047), threaded
    # explicitly (AR026: no ambient pin reads in the pipeline) into translation
    # so fingerprints hash the analyzed revision, not the live tree. Analyzer
    # passes without an index parameter still resolve through the documented
    # index.py ContextVar boundary.
    run_index = captured_index

    if spec.features.recall:
        speculative = sum(1 for c in scan.taint_chains if c.speculative)
        echo(
            f"Recall mode: widened taint discovery, {speculative} speculative "
            "chain(s) surfaced (marked low-confidence; adjudicate with --hunt --verify)."
        )
    if spec.features.secrets_history and not _deadline_hit("secrets_history"):
        from .secrets_history import scan_secret_history

        echo(f"Scanning the last {spec.features.secrets_history} commit(s) for secrets in git history…")

        def _history() -> None:
            history_hits, history_notes = scan_secret_history(repo_path, spec.features.secrets_history)
            scan.secret_history = history_hits
            scan.limitations.extend(history_notes)
            removed = sum(1 for h in history_hits if not h.still_in_head)
            echo(
                f"Secrets in history: {len(history_hits)} found, {removed} no longer in HEAD."
            )

        _timed(state, "secrets_history", _history)

    if spec.features.cve and scan.dependencies and not _deadline_hit("cve"):
        echo(f"Checking {len(scan.dependencies)} dependencies against OSV.dev…")

        def _cve() -> None:
            try:
                vulns, cve_summary = query_vulnerabilities(
                    scan.dependencies, progress=scan_progress
                )
            finally:
                scan_progress.done()
            scan.vulnerabilities = vulns
            echo(
                f"CVE lookup: {len(vulns)} vulnerabilit"
                f"{'y' if len(vulns) == 1 else 'ies'} across "
                f"{cve_summary.queried} query(s), {cve_summary.cached} cache hit(s), "
                f"{cve_summary.skipped_no_version} skipped (no queryable version), "
                f"{cve_summary.network_errors} network error(s)."
            )
            if cve_summary.inventory_only:
                listed = ", ".join(
                    f"{n} {eco}" for eco, n in sorted(cve_summary.inventory_only.items())
                )
                echo(
                    f"Not CVE-checked (no OSV.dev database for the ecosystem; inventory only): {listed}."
                )

        _timed(state, "cve", _cve)

    def _translate() -> None:
        analysis = translate_recon(scan, index=run_index)
        state.surfaces = analysis.attack_surfaces
        state.findings = analysis.findings
        state.paths = analysis.attack_paths
        state._architecture_md = summarize_architecture(scan)  # type: ignore[attr-defined]
        state._attack_surface_md = summarize_attack_surface(scan, analysis.attack_surfaces)  # type: ignore[attr-defined]

    _timed(state, "translate", _translate)
    findings = state.findings
    attack_paths = state.paths
    attack_surfaces = state.surfaces

    suppressed_findings: list = []
    suppression_governance: dict | None = None
    # Unconditional boundary check: even a minimal run (no optional stages
    # below) must notice a budget that expired during the scan stage.
    if spec.features.no_suppress or _deadline_hit("suppress"):
        if spec.features.suppress_file is not None and spec.features.no_suppress:
            echo("Note: --suppress-file is ignored because --no-suppress is set.", err=True)
    else:
        explicit = Path(spec.features.suppress_file) if spec.features.suppress_file else None
        if explicit is not None and not explicit.exists():
            raise AnalysisConfigurationError(f"Suppress file not found: {explicit}")

        def _suppress() -> None:
            nonlocal findings, suppressed_findings, suppression_governance
            id_aliases = None
            if spec.baseline is not None:
                # Migration aliases from the baseline let suppressions recorded
                # against pre-migration title ids keep applying (C13). A baseline
                # that fails to parse here fails authoritatively in the baseline
                # phase below; suppression simply runs unaliased until then.
                try:
                    records = [
                        {"id": snap.id, "title": snap.title, "rule_id": snap.rule_id}
                        for snap in load_baseline(Path(spec.baseline))
                    ]
                except (OSError, ValueError):
                    records = None
                if records is not None:
                    migration = legacy_id_aliases(records)
                    id_aliases = migration.aliases or None
                    for notice in migration.notices:
                        echo(f"Baseline identity notice: {notice}", err=True)
            try:
                suppset, sup_warnings = collect_suppressions(
                    repo_path,
                    findings,
                    explicit_file=explicit,
                    trusted_ref=spec.features.suppress_from_ref,
                    allow_pr_suppressions=spec.features.allow_pr_suppressions,
                    id_aliases=id_aliases,
                )
            except GitRefError as exc:
                raise AnalysisConfigurationError(str(exc)) from exc
            for warning in sup_warnings:
                echo(f"Suppression warning: {warning}", err=True)
            outcome = apply_suppressions(findings, suppset)
            for notice in outcome.notices:
                echo(f"Suppression warning: {notice}", err=True)
            findings = outcome.active
            suppressed_findings = outcome.suppressed
            state.findings = findings
            state.suppressed = suppressed_findings
            suppression_governance = {
                "pending": [f"{sup.label()} — {sup.reason} ({sup.source})" for sup in suppset.pending],
                "pending_applied": suppset.pending_applied,
                "trusted_ref": spec.features.suppress_from_ref,
                "by_rule": dict(Counter(s.rule for s in suppressed_findings)),
            }
            if suppset.pending:
                verb = "applied anyway (--allow-pr-suppressions)" if suppset.pending_applied else "NOT applied"
                echo(
                    f"{len(suppset.pending)} suppression(s) added since {spec.features.suppress_from_ref} — {verb}:",
                    err=True,
                )
                for line in suppression_governance["pending"]:
                    echo(f"  - {line}", err=True)
            if spec.features.strict_suppressions and suppset.expired:
                echo(
                    f"Error: {len(suppset.expired)} expired suppression(s) (--strict-suppressions).",
                    err=True,
                )
                raise AnalysisExit(2)
            if suppressed_findings:
                echo("")
                echo(f"Suppressed {len(suppressed_findings)} finding(s) (#144):")
                for summary_line in outcome.summary_lines():
                    echo(summary_line)

        _timed(state, "suppress", _suppress)
        findings = state.findings

    architecture_md = state._architecture_md
    attack_surface_md = state._attack_surface_md
    scan_report: dict[str, Any] | None = None
    analyzer_meta: list[dict[str, Any]] = []

    def _publish() -> None:
        nonlocal scan_report, analyzer_meta
        state.overlay = build_security_overlay(scan, attack_surfaces, findings, attack_paths)
        defensive_review_md = render_defensive_review(
            scan, attack_surfaces, findings, attack_paths, overlay=state.overlay
        )
        analyzer_meta = [
            {
                "name": metadata.name,
                "version": metadata.version if "version" in getattr(metadata, "model_fields_set", set()) else "legacy_unknown",
                "description": metadata.description,
                "scope": metadata.scope,
                "ecosystems": list(metadata.ecosystems),
            }
            for metadata in (get_analyzer_metadata(a) for a in state.analyzers)
        ]
        try:
            scan_report = write_reports(
                output,
                scan,
                architecture_md,
                attack_surface_md,
                defensive_review_md,
                attack_surfaces,
                findings,
                attack_paths,
                analyzer_metadata=analyzer_meta,
                suppressed=suppressed_findings,
                output_format=spec.output_format,
                overlay=state.overlay,
            )
        except UnsafePathError as exc:
            echo(f"Error: {exc}", err=True)
            raise AnalysisExit(2) from exc
        write_run_manifest(state, output)
        echo(render_console_summary(scan, findings, attack_paths))
        _warn_if_nothing_scanned(scan, echo)
        echo("")
        echo(f"Reports written to: {output.resolve()}")

    _timed(state, "publish", _publish)

    diff_exit_code = 0
    diff = None
    if spec.baseline is not None and not _deadline_hit("baseline"):
        with _diagnostic_phase(state, "baseline"):
            baseline_path = Path(spec.baseline)
            try:
                baseline_snapshots = load_baseline(baseline_path)
            except (OSError, ValueError) as exc:
                raise AnalysisConfigurationError(f"Failed to read baseline: {exc}") from exc
            current_snapshots = [FindingSnapshot.from_finding(f) for f in findings]
            from .comparison import coverage_from_report
            diff = diff_findings(
                baseline_snapshots,
                current_snapshots,
                suppressed=[FindingSnapshot.from_finding(s.finding) for s in suppressed_findings],
                current_coverage=coverage_from_report({"scan": scan.model_dump(
                    include={"scanned_files", "analyzer_errors", "limitations"}
                )}),
            )
            counts = diff.counts()
            echo("")
            echo(
                f"Diff vs baseline: {counts['new']} new, "
                f"{counts['new_instances']} new instance(s) of existing findings, "
                f"{counts['persisted']} persisted, {counts['resolved']} resolved, "
                f"{counts['newly_suppressed']} newly suppressed, "
                f"{counts['resolution_uncertain']} resolution uncertain."
            )
            for note in diff.coverage_notes:
                echo(f"Note: {note}", err=True)
            if diff.baseline_without_instances:
                echo(
                    "Note: the baseline predates per-instance fingerprints (attackmap < 0.4.32); "
                    "new instances of existing findings can't be detected until it is regenerated.",
                    err=True,
                )
            diff_path = Path(spec.diff_output) if spec.diff_output else output / "attackmap-diff.md"
            _write_text(diff_path, render_diff_markdown(diff))
            echo(f"Diff written to: {diff_path.resolve()}")
            if spec.fail_on_new_high and diff.has_new_high:
                new_high_titles = [s.title for s in diff.new if s.severity == "high"] + [
                    f"{s.title} (new instance(s): {', '.join(labels[:5])})"
                    for s, labels in diff.new_instances
                    if s.severity == "high"
                ]
                echo("", err=True)
                echo(
                    "New HIGH findings introduced (failing per --fail-on-new-high):",
                    err=True,
                )
                for t in new_high_titles:
                    echo(f"  - {t}", err=True)
                diff_exit_code = 1
            if spec.fail_on_new_suppression and diff.newly_suppressed:
                echo("", err=True)
                echo(
                    "Findings newly suppressed by this change (failing per --fail-on-new-suppression):",
                    err=True,
                )
                for s_ in diff.newly_suppressed:
                    echo(f"  - [{s_.severity.upper()}] {s_.title}", err=True)
                diff_exit_code = 1

    if spec.pr_comment is not None and not _deadline_hit("pr_comment"):
        with _diagnostic_phase(state, "pr_comment"):
            pr_path = Path(spec.pr_comment)
            _write_text(pr_path, render_pr_comment(findings, diff, suppressions=suppression_governance))
            echo(f"PR comment written to: {pr_path.resolve()}")

    def _add_usage(usage: dict[str, int] | None) -> None:
        if not usage:
            return
        for key, value in usage.items():
            if isinstance(value, int):
                state.llm_usage[key] = state.llm_usage.get(key, 0) + value

    if ai.enabled and not _deadline_hit("llm"):
        with _diagnostic_phase(state, "llm"):
            try:
                effort_value = ai.effort
                echo("")
                echo(
                    f"Generating narrative review via {llm_display} (backend={ai.backend}, may take a minute)..."
                )
                scan_progress.stage(
                    f"{llm_display} is writing the defensive review (backend={ai.backend})"
                )
                try:
                    result = generate_llm_review(
                        scan,
                        attack_surfaces,
                        findings,
                        attack_paths,
                        model=ai.model,
                        effort=effort_value,  # type: ignore[arg-type]
                        backend=ai.backend,  # type: ignore[arg-type]
                        speed=ai.speed,  # type: ignore[arg-type]
                        provider=ai.provider,  # type: ignore[arg-type]
                    )
                finally:
                    scan_progress.done()
            except LlmReviewError as exc:
                echo(f"LLM review skipped: {exc}", err=True)
            else:
                _add_usage(result.usage)
                llm_md_path = output / "defensive-review-llm.md"
                _write_text(llm_md_path, sanitize_llm_markdown(result.markdown) + "\n")
                llm_meta_path = output / "defensive-review-llm.meta.json"
                _write_text(
                    llm_meta_path,
                    json.dumps(
                        {
                            "backend": result.backend,
                            "model": result.model,
                            "stop_reason": result.stop_reason,
                            "usage": result.usage,
                            "usage_status": getattr(result, "usage_status", "unknown"),
                            "reference_validation": getattr(result, "reference_validation", None),
                        },
                        indent=2,
                    )
                    + "\n",
                )
                state.ai_outputs["review"] = bool(result.markdown.strip())
                echo(f"LLM review written to: {llm_md_path.resolve()} (backend={result.backend})")

    if ai.hunt and not _deadline_hit("hunt"):
        with _diagnostic_phase(state, "hunt"):
            hunt_effort_value = ai.effort
            echo("")
            lens_count = ai.hunt_lenses
            jury_votes = ai.verify_votes
            max_rounds = ai.hunt_rounds
            token_budget = ai.hunt_budget if ai.hunt_budget > 0 else None
            use_jury = ai.verify and (jury_votes > 1 or lens_count > 1 or max_rounds > 1)
            lens_names = [name for name, _ in HUNT_LENSES][:lens_count] if lens_count > 1 else None

            def _hunt_llm_call(mode: str, hypotheses=None, lens=None, avoid_titles=None, critic_hint=None):
                return generate_llm_review(
                    scan,
                    attack_surfaces,
                    findings,
                    attack_paths,
                    model=ai.model,
                    effort=hunt_effort_value,  # type: ignore[arg-type]
                    backend=ai.backend,  # type: ignore[arg-type]
                    mode=mode,  # type: ignore[arg-type]
                    speed=ai.speed,  # type: ignore[arg-type]
                    provider=ai.provider,  # type: ignore[arg-type]
                    hypotheses=hypotheses,
                    lens=lens,
                    avoid_titles=avoid_titles,
                    critic_hint=critic_hint,
                )

            hunt_extra_meta: dict = {}
            try:
                if use_jury:
                    lens_note = f", {lens_count} lenses" if lens_names else ""
                    round_note = f", up to {max_rounds} rounds" if max_rounds > 1 else ""
                    echo(
                        f"Hunting + adjudicating via {llm_display} "
                        f"({jury_votes} independent skeptics{lens_note}{round_note}, backend={ai.backend}, may take a few minutes)..."
                    )
                    scan_progress.stage(
                        f"{llm_display} is hunting + majority-vote verifying "
                        f"({jury_votes} skeptics{lens_note}{round_note}, backend={ai.backend})"
                    )
                    try:
                        jury = run_majority_verify(
                            scan, attack_surfaces, findings, attack_paths,
                            votes=jury_votes, llm_call=_hunt_llm_call, lenses=lens_names,
                            max_rounds=max_rounds, token_budget=token_budget,
                        )
                    finally:
                        scan_progress.done()
                    hunt_markdown = jury.report
                    hunt_backend, hunt_model = jury.backend, jury.model
                    hunt_stop, hunt_usage = None, jury.usage
                    hunt_extra_meta = {
                        "allowance": getattr(jury, "allowance", {}),
                        "citation_context": getattr(jury, "citation_context", {}),
                        "verify_votes": jury.votes,
                        "assessment_kind": jury.assessment_kind,
                        "failed_passes": jury.failed_passes,
                        "abstained_votes": sum(c.abstained for c in jury.consensus),
                        "lenses": lens_names or [],
                        "rounds_run": jury.rounds,
                        "hypothesis_count": jury.hypothesis_count,
                        "consensus": {
                            "confirmed": sum(1 for c in jury.consensus if c.verdict == "confirmed"),
                            "needs_review": sum(1 for c in jury.consensus if c.verdict == "needs_review"),
                            "refuted": sum(1 for c in jury.consensus if c.verdict == "refuted"),
                            "inconclusive": sum(1 for c in jury.consensus if c.verdict == "inconclusive"),
                        },
                    }
                else:
                    hunt_mode = "hunt_verify" if ai.verify else "hunt"
                    echo(
                        f"Hunting for vulnerability hypotheses via {llm_display} "
                        f"({'adjudicated against source, ' if ai.verify else ''}backend={ai.backend}, may take a minute)..."
                    )
                    scan_progress.stage(
                        f"{llm_display} is hunting exploit-chain hypotheses"
                        f"{' + verifying against source' if ai.verify else ''} (backend={ai.backend})"
                    )
                    try:
                        hunt_result = _hunt_llm_call(hunt_mode)
                    finally:
                        scan_progress.done()
                    hunt_markdown = hunt_result.markdown
                    hunt_backend, hunt_model = hunt_result.backend, hunt_result.model
                    hunt_stop, hunt_usage = hunt_result.stop_reason, hunt_result.usage
                    hunt_extra_meta["usage_status"] = getattr(hunt_result, "usage_status", "unknown")
            except LlmReviewError as exc:
                echo(f"Vulnerability hunt skipped: {exc}", err=True)
            else:
                _add_usage(hunt_usage if isinstance(hunt_usage, dict) else None)
                hunt_md_path = output / "vulnerability-hypotheses.md"
                _write_text(hunt_md_path, HUNT_BANNER + sanitize_llm_markdown(hunt_markdown) + "\n")
                hunt_meta_path = output / "vulnerability-hypotheses.meta.json"
                _write_text(
                    hunt_meta_path,
                    json.dumps(
                        {
                            "backend": hunt_backend,
                            "model": hunt_model,
                            "stop_reason": hunt_stop,
                            "usage": hunt_usage,
                            **hunt_extra_meta,
                        },
                        indent=2,
                    )
                    + "\n",
                )
                state.ai_outputs["hunt_verify" if ai.verify else "hunt"] = bool(hunt_markdown.strip()) and hunt_backend in {"api", "cli"}
                echo(
                    f"Vulnerability hypotheses written to: {hunt_md_path.resolve()} "
                    f"(backend={hunt_backend})"
                )

    if ai.remediate and not _deadline_hit("remediate"):
        with _diagnostic_phase(state, "remediate"):
            try:
                rem_effort_value = ai.effort
                echo("")
                echo(
                    f"Generating remediation suggestions via {llm_display} (backend={ai.backend}, may take a minute)..."
                )
                scan_progress.stage(
                    f"{llm_display} is drafting remediation suggestions (backend={ai.backend})"
                )
                try:
                    rem_result = generate_llm_review(
                        scan,
                        attack_surfaces,
                        findings,
                        attack_paths,
                        model=ai.model,
                        effort=rem_effort_value,  # type: ignore[arg-type]
                        backend=ai.backend,  # type: ignore[arg-type]
                        mode="remediate",
                        speed=ai.speed,  # type: ignore[arg-type]
                        provider=ai.provider,  # type: ignore[arg-type]
                    )
                finally:
                    scan_progress.done()
            except LlmReviewError as exc:
                echo(f"Remediation skipped: {exc}", err=True)
            else:
                _add_usage(rem_result.usage)
                rem_md_path = output / "remediation.md"
                _write_text(rem_md_path, REMEDIATION_BANNER + sanitize_llm_markdown(rem_result.markdown) + "\n")
                rem_meta_path = output / "remediation.meta.json"
                _write_text(
                    rem_meta_path,
                    json.dumps(
                        {
                            "backend": rem_result.backend,
                            "model": rem_result.model,
                            "stop_reason": rem_result.stop_reason,
                            "usage": rem_result.usage,
                            "usage_status": getattr(rem_result, "usage_status", "unknown"),
                            "reference_validation": getattr(rem_result, "reference_validation", None),
                        },
                        indent=2,
                    )
                    + "\n",
                )
                state.ai_outputs["remediate"] = bool(rem_result.markdown.strip())
                echo(
                    f"Remediation suggestions written to: {rem_md_path.resolve()} "
                    f"(backend={rem_result.backend})"
                )

    if ai.triage and not _deadline_hit("triage"):
        with _diagnostic_phase(state, "triage"):
            tri_effort_value = ai.effort
            tri_md_path = output / "triage.md"
            tri_meta_path = output / "triage.meta.json"
            tri_backend = "deterministic"
            tri_model: str | None = None
            tri_stop: str | None = None
            tri_usage: dict = {}
            tri_usage_status = "unknown"
            tri_reference_validation = None
            try:
                echo("")
                echo(
                    f"Triaging findings via {llm_display} (backend={ai.backend})..."
                )
                scan_progress.stage(f"{llm_display} is triaging findings (backend={ai.backend})")
                try:
                    tri_result = generate_llm_review(
                        scan,
                        attack_surfaces,
                        findings,
                        attack_paths,
                        model=ai.model,
                        effort=tri_effort_value,  # type: ignore[arg-type]
                        backend=ai.backend,  # type: ignore[arg-type]
                        mode="triage",
                        speed=ai.speed,  # type: ignore[arg-type]
                        provider=ai.provider,  # type: ignore[arg-type]
                    )
                finally:
                    scan_progress.done()
                markdown = TRIAGE_BANNER + tri_result.markdown + "\n"
                tri_backend = tri_result.backend
                tri_model = tri_result.model
                tri_stop = tri_result.stop_reason
                tri_usage = tri_result.usage
                tri_usage_status = getattr(tri_result, "usage_status", "unknown")
                tri_reference_validation = getattr(tri_result, "reference_validation", None)
                _add_usage(tri_usage)
            except LlmReviewError as exc:
                echo(f"Triage LLM unavailable ({exc}); using deterministic ordering.", err=True)
                markdown = TRIAGE_BANNER + render_triage_fallback(scan, findings) + "\n"
            _write_text(tri_md_path, sanitize_llm_markdown(markdown))
            _write_text(
                tri_meta_path,
                json.dumps(
                    {
                        "backend": tri_backend,
                        "model": tri_model,
                        "stop_reason": tri_stop,
                        "usage": tri_usage,
                        "usage_status": tri_usage_status,
                        "reference_validation": tri_reference_validation,
                    },
                    indent=2,
                )
                + "\n",
            )
            state.ai_outputs["triage"] = tri_backend != "deterministic" and bool(tri_result.markdown.strip())
            echo(f"Triage shortlist written to: {tri_md_path.resolve()} (backend={tri_backend})")

    state.exit_code = diff_exit_code
    state.finish_scan("completed")
    write_run_manifest(state, output)

    # The run is over: drop this thread's snapshot pin so later operations on
    # the same repo (report regeneration, a follow-up scan) don't read a stale
    # captured revision (C33/AM047). The next scan re-pins on its own build.
    clear_pinned_index()

    if scan_report is not None and spec.output_format in {"all", "json"}:
        write_artifact_manifest(
            output,
            run_id=spec.run_id or make_run_id(),
            engine_version=__version__,
            repo_root=str(repo_path),
            repo_name=repo_path.name,
            analyzer_metadata=analyzer_meta,
            exit_code=state.exit_code,
            status="succeeded" if state.exit_code == 0 else "policy_failed",
            report_data=scan_report,
            output_format=spec.output_format,
        )

    return state


def run_scan(
    spec: RunSpec,
    *,
    repo_path: Path,
    output: Path,
    analyzers: list | None = None,
    echo: Callable[..., None] = emit_text,
) -> RunState:
    """Run one repository configured by ``spec`` (AR025: the only run config).

    Shares one AI allowance across every AI feature without replacing an
    already-active caller ledger, and validates the AI allowance bounds when
    any AI feature is enabled.
    """
    ai = spec.ai
    kwargs = {"repo_path": repo_path, "output": output, "analyzers": analyzers, "echo": echo}
    if not (ai.enabled or ai.hunt or ai.remediate or ai.triage):
        return _run_scan_published(spec, **kwargs)
    for name, maximum in (("max_calls", 64), ("output_tokens", 256000), ("timeout_seconds", 86400)):
        value = getattr(ai, name)
        if type(value) is not int or not 1 <= value <= maximum:
            raise AnalysisConfigurationError(f"AI {name} must be an integer from 1 to {maximum}.")
    if current_budget() is not None:
        return _run_scan_published(spec, **kwargs)
    with budget_scope(AiBudget(max_calls=ai.max_calls, max_seconds=ai.timeout_seconds,
                               output_token_limit=ai.output_tokens)):
        return _run_scan_published(spec, **kwargs)


def _flush_event_log(state: RunState, folder: Path) -> None:
    """Persist the run's event log into the staged generation (AR003).

    Called before ``publish_generation`` so a committed generation always
    carries its ``events.jsonl``. Extra files are not part of the artifact
    manifest, so validation is unaffected.
    """
    if state.events is None or not state.events.records():
        return
    safe_write_text(folder, folder / "events.jsonl",
                    "".join(json.dumps(r, ensure_ascii=False) + "\n"
                            for r in state.events.records()))


def _run_scan_published(
    spec: RunSpec,
    *,
    repo_path: Path,
    output: Path,
    analyzers: list | None = None,
    echo: Callable[..., None] = emit_text,
) -> RunState:
    """Publish one validated generation; flat files are compatibility exports."""
    kwargs = {"repo_path": repo_path, "output": output, "analyzers": analyzers, "echo": echo}
    if not spec.atomic_output:
        state = RunState(spec=spec)
        try:
            return _run_scan(spec, state=state, **kwargs)
        except BaseException as exc:
            from .artifact_publisher import write_diagnostic
            outcome = "cancelled" if isinstance(exc, KeyboardInterrupt) else "failed"
            state.finish_scan(outcome)
            with suppress(OSError, ValueError):
                write_diagnostic(Path(output), spec.run_id or make_run_id(), state=outcome,
                                 scan_timing=state.scan_timing(), context=_diagnostic_context(state, outcome))
            raise
    from .artifact_publisher import (
        export_compatibility,
        generation_dir,
        prepare_output_root,
        publish_generation,
        write_diagnostic,
    )
    base = prepare_output_root(Path(output))
    run_id = spec.run_id or make_run_id()
    folder = generation_dir(base, run_id)
    staged = replace(spec, output_format="all", run_id=run_id, atomic_output=False)
    state = RunState(spec=staged)
    try:
        ensure_output_dir(folder, mark=True)
        state = _run_scan(staged, state=state, output=folder, **{k: v for k, v in kwargs.items() if k != "output"})
        with _diagnostic_phase(state, "publication"):
            _flush_event_log(state, folder)
            publish_generation(base, run_id)
    except BaseException as exc:
        outcome = "cancelled" if isinstance(exc, KeyboardInterrupt) else "failed"
        state.finish_scan(outcome)
        if state.events is not None and state.events.records():
            # Best effort only; the diagnostic below still records the failure.
            with suppress(OSError, ValueError):
                state.events.stage("publication", outcome, detail=type(exc).__name__)
                _flush_event_log(state, folder)
        with suppress(OSError, ValueError):
            write_diagnostic(base, run_id, state=outcome, scan_timing=state.scan_timing(),
                             context=_diagnostic_context(state, outcome))
        raise
    # Publication is already committed. A failed convenience export must not
    # turn the authoritative successful generation into a failed execution.
    try:
        export_compatibility(base, folder, output_format=spec.output_format)
    except (OSError, ValueError):
        state.errors.append({"stage": "compatibility_export",
                             "error": "Flat export failed; the published generation remains available."})
        echo("Warning: flat export failed; the published generation remains available.", err=True)
    from .retention import retain_after_publish
    retain_after_publish(base, echo=echo)
    state.spec = spec
    return state
